USE VIVA_LEARNING;

SHOW TABLES;

DESC employees;

SELECT * FROM employees;


SELECT DEPT_ID, COUNT(*) 
FROM employees
GROUP BY DEPT_ID
HAVING COUNT(*) > 2;


SELECT DEPT_ID, SUM(SALARY)
FROM employees
GROUP BY DEPT_ID
HAVING SUM(SALARY) > 80000;

SELECT DEPT_ID, AVG(SALARY) FROM employees
GROUP BY DEPT_ID
HAVING AVG(SALARY) > 80000;

SELECT DEPT_ID, MAX(SALARY) AS MAX_SALARY
FROM employees
GROUP BY DEPT_ID
HAVING MAX(SALARY) > 40000;

SELECT DEPT_ID , AVG(SALARY) AS AVERAGE_SALARY , COUNT(*) AS TOTAL_EMPLOYEES
FROM EMPLOYEES
GROUP BY DEPT_ID
HAVING AVG(SALARY) > 30000 AND COUNT(*) > 1;

SELECT DEPT_ID, MAX(SALARY) AS MAX_SALARY
FROM employees 
GROUP BY DEPT_ID
HAVING MAX(SALARY) < 50000 ;

SELECT DEPT_ID, COUNT(*) AS TOTAL_EMPLOYEES , SUM(SALARY) 
FROM employees
GROUP BY DEPT_ID
HAVING COUNT(*) >= 3 AND SUM(SALARY) > 100000;
